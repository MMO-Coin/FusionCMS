const {test, expect, login, openPage, verify, fixture} = require('./helpers.cjs');

test('news, inbox and sent pages keep fixed sizes and do not overlap with cached tied timestamps', async ({page}) => {
    fixture('seed-public-lists');
    const titles = () => page.locator('.news-title').allTextContents();
    await openPage(page, '/news');
    await expect(page.locator('.news-title')).toHaveCount(10);
    expect((await titles())[0].trim()).toBe('Page article 67');
    await page.goto('/news/10');
    const second = await titles();
    expect(second.map(text => text.trim())).toEqual(Array.from({length: 10}, (_, i) => 'Page article ' + (57 - i)));
    await page.goto('/news/20');
    const third = await titles();
    expect(third).toHaveLength(10);
    expect(second.filter(title => third.includes(title))).toEqual([]);
    await page.goto('/news/99999');
    await expect(page.locator('.news-title')).toHaveCount(7);
    await login(page);
    await page.goto('/messages');
    const inboxTitles = () => page.locator('#pm_inbox tbody tr td:nth-child(2)').allTextContents();
    await expect(page.locator('#pm_inbox tbody tr')).toHaveCount(10);
    expect((await inboxTitles())[0].trim()).toBe('Page message 30');
    await page.goto('/messages/page/10');
    expect((await inboxTitles()).map(text => text.trim())).toEqual(Array.from({length: 10}, (_, i) => 'Page message ' + (20 - i)));
    await page.goto('/messages/page/20');
    await expect(page.locator('#pm_inbox tbody tr')).toHaveCount(10);
    await expect(page.locator('#pm_inbox').getByRole('link', {name: /Older/})).toHaveCount(0);
    await expect(page.locator('#pm_inbox').getByRole('link', {name: /Newer/})).toHaveCount(1);
    await page.goto('/messages/page/0/20');
    await expect(page.locator('#pm_sent')).toBeVisible();
    await expect(page.locator('#pm_sent tbody tr')).toHaveCount(10);
    await expect(page.locator('#pm_sent tbody tr').first()).toContainText('Page message 40');
    await expect(page.locator('#pm_sent').getByRole('link', {name: /Older/})).toHaveCount(0);
    await expect(page.locator('#pm_sent').getByRole('link', {name: /Newer/})).toHaveCount(1);
});

test('comments page in batches, recover from failed requests and retain the draft until a successful post', async ({page}) => {
    await login(page);
    fixture('seed-public-lists');
    await page.route('**/news/comments/get/67', route => route.fulfill({status: 503, body: 'Unavailable'}));
    await page.goto('/news/view/67');
    await expect(page.getByRole('button', {name: 'Try again', exact: true})).toBeVisible();
    await page.unroute('**/news/comments/get/67');
    await page.getByRole('button', {name: 'Try again', exact: true}).click();
    const comments = page.locator('#comments_area_67 .comment');
    await expect(comments).toHaveCount(25);
    await expect(comments.first()).toContainText('Page comment 70');
    const field = page.locator('#comment_field_67');
    await field.fill('Draft after offline');
    await page.route('**/news/comments/add/67', route => route.fulfill({status: 503, body: 'Unavailable'}));
    await page.locator('#comment_button_67').click();
    await expect(page.locator('#comment_error_67')).toContainText('Your draft is still here');
    await expect(field).toHaveValue('Draft after offline');
    await expect(field).toBeEnabled();
    await expect(page.locator('#comment_button_67')).toBeEnabled();
    await page.unroute('**/news/comments/add/67');
    await page.locator('#comment_button_67').click();
    await expect(comments).toHaveCount(26);
    await expect(field).toHaveValue('');
    await expect(comments.first()).toContainText('Draft after offline');
    await page.route('**/news/comments/page/67?*', route => route.fulfill({status: 503, body: 'Unavailable'}));
    await page.getByRole('button', {name: 'Load more comments', exact: true}).click();
    await expect(page.locator('.comment-page > .comment-error')).toContainText('Unable to load comments');
    await expect(page.getByRole('button', {name: 'Load more comments', exact: true})).toBeEnabled();
    await page.unroute('**/news/comments/page/67?*');
    await page.getByRole('button', {name: 'Load more comments', exact: true}).click();
    await expect(comments).toHaveCount(51);
    await page.getByRole('button', {name: 'Load more comments', exact: true}).click();
    await expect(comments).toHaveCount(71);
    const ids = await comments.evaluateAll(rows => rows.map(row => row.id));
    expect(new Set(ids).size).toBe(71);
    await expect(page.getByRole('button', {name: 'Load more comments', exact: true})).toHaveCount(0);
    await page.goto('/logout');
    await login(page, 'E2EOWNER');
    await page.goto('/news/view/67');
    await expect(comments).toHaveCount(25);
    const first = comments.first();
    const deletedId = await first.getAttribute('id');
    await page.route('**/news/comments/delete/*', route => route.fulfill({status: 503, body: 'Unavailable'}));
    await first.getByRole('button', {name: 'Delete', exact: true}).click();
    await expect(first.locator('.comment-error')).toContainText('Unable to delete');
    await expect(page.locator('[id="' + deletedId + '"]')).toBeVisible();
    await page.unroute('**/news/comments/delete/*');
    await first.getByRole('button', {name: 'Delete', exact: true}).click();
    await expect(page.locator('[id="' + deletedId + '"]')).toHaveCount(0);
});

test('admin account search counts all matches but returns bounded deterministic pages', async ({page}) => {
    fixture('seed-public-lists');
    await login(page, 'E2EOWNER');
    expect((await (await verify(page, '/admin', {send: '1', security_code: 'BrowserFixtureOnly'})).text()).trim()).toBe('welcome');
    const query = async data => (await verify(page, '/admin/accounts/get_accs_ajax', {draw: '1', search: 'AUDIT', start: '0', length: '10', ...data})).json();
    const large = await query({length: '999999'});
    expect(large.recordsFiltered).toBe(125);
    expect(large.data).toHaveLength(100);
    expect(large.data[0].id).toBe('100');
    const last = await query({start: '100', length: '100'});
    expect(last.data).toHaveLength(25);
    expect(last.data[0].id).toBe('200');
    expect((await query({length: '-1'})).data).toEqual([]);
    expect((await query({search: '%'})).recordsFiltered).toBe(0);
    await page.goto('/admin/accounts');
    await page.locator('#acclist_filter input').fill('AUDIT');
    await expect(page.locator('#acclist tbody tr')).toHaveCount(10);
    await expect(page.locator('#acclist tbody tr').first()).toContainText('AUDIT100');
});
